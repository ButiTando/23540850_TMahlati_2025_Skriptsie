/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MPU Configuration--------------------------------------------------------*/
  MPU_Config();

  /* USER CODE BEGIN MPU_Post */
  /* The D2 domain SRAMs are gated off after reset. The ETH descriptors, the Rx
     pbuf pool and the LwIP heap all live there, so they must be clocked before
     anything touches them. */
  __HAL_RCC_D2SRAM1_CLK_ENABLE();
  __HAL_RCC_D2SRAM2_CLK_ENABLE();

  /* Safe to enable now that D2 SRAM is mapped non-cacheable by the MPU above. */
  SCB_EnableICache();
  SCB_EnableDCache();
  /* USER CODE END MPU_Post */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_LWIP_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();
  MX_TIM4_Init();
  MX_TIM5_Init();
  MX_TIM23_Init();
  MX_TIM24_Init();
  MX_RTC_Init();
  MX_TIM12_Init();
  MX_TIM1_Init();
  MX_USART3_UART_Init();
  /* USER CODE BEGIN 2 */
// RTC timer start

// Start timers
// Start slave timer first
  HAL_TIM_Base_Start(&htim1);
  HAL_TIM_Base_Start(&htim12);

// Start master timers
  HAL_TIM_Base_Start(&htim2);
  HAL_TIM_Base_Start(&htim3);
  HAL_TIM_Base_Start(&htim4);
  HAL_TIM_Base_Start(&htim5);
  HAL_TIM_Base_Start(&htim23);
  HAL_TIM_Base_Start(&htim24);



// The listener binds now; the outbound link dials when DHCP is done.
  tcpOpt.huart = &huart3;
  start_tcp_server(&tcpOpt);
  start_tcp_client(&tcpOpt);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  uint32_t ticks_pass = 0;
  uint32_t lwip_ticks = 0;
  uint32_t period_s = 1;          // settable at runtime by SET_PERIOD
  int32_t interval = STARTUP_INTERVAL_MS;

  while (1)
  {
	  uint32_t ticks = HAL_GetTick();

//	  Apply anything the control station has sent.
	  uint32_t command_word = 0;
	  if(tcp_server_take_command(&tcpOpt, &command_word)){
		  char reply[64];
		  if(BLM_HandleCommand(&hrtc, command_word, &period_s) == HAL_OK){
			  snprintf(reply, sizeof(reply), "Applied command %08lX (period %lus)\n",
					   (unsigned long)command_word, (unsigned long)period_s);
		  }
		  else{
			  snprintf(reply, sizeof(reply), "Rejected command %08lX\n",
					   (unsigned long)command_word);
		  }
		  tcp_uart_print(&huart3, reply);
	  }

	  if(ticks-ticks_pass>interval){

		  GenerateChannelCSV(&hrtc, &channel1, &channel2, &channel3, &channel4, &channel5, &channel6, message, MESSAGE_LEN);
//		  UART is the debug view; the network carries the real data.
		  HAL_UART_Transmit_IT(&huart3, (uint8_t*)message, strlen(message));
		  tcp_client_send(message, strlen(message), &tcpOpt);
		  ticks_pass = HAL_GetTick();

	  }

//	  Fast for the first few seconds, then the configured period.
	  if(ticks>STARTUP_DURATION_MS){
		  interval = (int32_t)(period_s * 1000U);
	  }
	  if(HAL_GetTick()-lwip_ticks > 1){
		  MX_LWIP_Process();
		  lwip_ticks = HAL_GetTick();
	  }

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

